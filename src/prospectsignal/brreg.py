"""Brønnøysundregistrene's open Enhetsregisteret API: bulk download, single lookups, attribution.

Verified against the official documentation (https://data.brreg.no/enhetsregisteret/api/dokumentasjon/no/index.html)
and live responses on 2026-10-01:

- Bulk files: ``/api/enheter/lastned/csv`` (~155 MB gzip) and ``/api/underenheter/lastned/csv`` (gzip CSV).
  Produced every night around 05:00; ``etag`` and ``last-modified`` tell whether a file has changed. Cells are all
  quoted and may contain line breaks and doubled quotes.
- Search (``/api/enheter``) is capped at 10 000 results per query, so the bulk files are the supported way to get
  the whole register. Single lookups: ``/api/enheter/{orgnr}`` and ``/api/underenheter/{orgnr}``; an unknown
  number returns 404.
- Copies must drop units that are removed from open data ("Fjernet"); a full bulk reload does that.
- ``antallAnsatte`` is null for 0-4 employees; ``harRegistrertAntallAnsatte`` tells 0 from 1-4.
- No rate limit is published in the documentation (TODO(verify) with opendata@brreg.no). Prospect Signal makes
  requests only when the user asks, one at a time.
- Licence: Norsk lisens for offentlige data (NLOD) 2.0. Attribution wording follows NLOD § 5.
"""

